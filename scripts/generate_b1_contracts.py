"""Generate B1 schemas and structural DTOs from the Python contract models."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "AgentCut-ai"))
from app.schemas.script_contracts_v1 import (  # noqa: E402
    ScriptContractBundleV1, MaterialIndexV1, DirectorDecisionV1, EditingScriptV1,
    AnalyzeInputV1, TaskSubmissionV1, TaskEventV1,
)


def render_files():
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:agentcut:script-contract-bundle:v1",
        **ScriptContractBundleV1.model_json_schema(),
    }
    definitions = schema["$defs"]
    java_models = {**definitions, "ScriptContractBundleV1": schema}

    def ts_type(node):
        if "$ref" in node:
            return node["$ref"].split("/")[-1]
        if "anyOf" in node:
            return " | ".join(ts_type(branch) for branch in node["anyOf"])
        if "const" in node:
            return json.dumps(node["const"])
        if "enum" in node:
            return " | ".join(json.dumps(value) for value in node["enum"])
        kind = node.get("type")
        if kind == "array":
            return f"Array<{ts_type(node['items'])}>"
        return {"integer": "number", "number": "number", "boolean": "boolean", "null": "null", "string": "string"}[kind]

    def java_type(node, nullable=False):
        if "$ref" in node:
            return node["$ref"].split("/")[-1]
        if "anyOf" in node:
            return java_type(next(branch for branch in node["anyOf"] if branch.get("type") != "null"), True)
        kind = node.get("type", "string")
        if kind == "array":
            return f"List<{java_type(node['items'], True)}>"
        return {
            "integer": "Long" if nullable else "long",
            "number": "Double" if nullable else "double",
            "boolean": "Boolean" if nullable else "boolean",
            "string": "String",
        }[kind]

    ts = "/** Generated by scripts/generate_b1_contracts.py. Do not edit. */\n"
    ts += "/** Ranges are integer milliseconds; nullable fields remain explicitly present. */\n\n"
    java = "// Generated by scripts/generate_b1_contracts.py. Do not edit.\n"
    java += "package cn.sutone.cut.api.dto.script;\n\nimport java.util.List;\n\n"
    java += "public final class B1TypesV1 {\n    private B1TypesV1() {}\n\n"
    for name, node in java_models.items():
        props = node["properties"]
        ts += f"export interface {name} {{\n"
        ts += "".join(f"  {field}: {ts_type(shape)};\n" for field, shape in props.items())
        ts += "}\n\n"
        fields = ",\n            ".join(f"{java_type(shape)} {field}" for field, shape in props.items())
        java += f"    public record {name}(\n            {fields}) {{}}\n\n"
    java += "}\n"
    content = lambda node: json.dumps(node, ensure_ascii=False, indent=2) + "\n"
    files = {
        ROOT / "docs/contracts/script-contract-bundle-v1.schema.json": content(schema),
        ROOT / "AgentCut-backend/sutone-agent-cut-api/src/main/resources/contracts/script-contract-bundle-v1.schema.json": content(schema),
        ROOT / "AgentCut-backend/sutone-agent-cut-api/src/main/java/cn/sutone/cut/api/dto/script/B1TypesV1.java": java,
        ROOT / "AgentCut-front/src/types/scriptContractsV1.ts": ts,
    }
    for name, model in {
        "material-index": MaterialIndexV1, "director-decision": DirectorDecisionV1,
        "editing-script": EditingScriptV1, "analyze-input": AnalyzeInputV1,
        "task-submission": TaskSubmissionV1, "task-event": TaskEventV1,
    }.items():
        files[ROOT / f"docs/contracts/{name}-v1.schema.json"] = content({
            "$schema": schema["$schema"], "$id": f"urn:agentcut:{name}:v1",
            **model.model_json_schema(),
        })
    return files


if __name__ == "__main__":
    for path, text in render_files().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
